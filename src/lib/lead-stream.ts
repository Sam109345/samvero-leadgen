let streamCounter = 0;

/**
 * Returns a new realistic incoming lead with calculated business age and pre-synthesized website
 */
export function generateNextIncomingLead(): Lead {
  // Check if live stream buffer has fresh leads from live APIs (Freelancer.com, RemoteOK, Remotive, GMB)
  const bufferedLead = getNextBufferedLiveLead();
  if (bufferedLead) {
    const liveLead: Lead = {
      ...bufferedLead,
      id: `stream-${bufferedLead.id}-${Date.now().toString().slice(-4)}`,
      postedAt: 'Just now (Live Feed)',
      timeAgo: 'Just now',
      incomingAt: Date.now(),
    };
    registerLead(liveLead);
    return liveLead;
  }

  const template = incomingLeadTemplates[streamCounter % incomingLeadTemplates.length];
  streamCounter++;

  const id = `demo-stream-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`;
  const businessAge = calculateBusinessAge(template.foundedDate);

  const cleanContact = {
    ...template.contact,
    contactPerson: undefined, // Enforce Real-Data Policy: Do not fabricate personal contact names
  };

  const baseLead: Lead = {
    id,
    title: template.title,
    businessName: template.businessName,
    type: template.type,
    platform: template.platform,
    category: template.category,
    country: template.country,
    city: template.city,
    address: template.address,
    businessAge,
    budget: template.budget,
    jobType: template.jobType,
    description: template.description,
    postedAt: 'Just now (DEMO)',
    contact: cleanContact,
    rating: template.rating,
    reviewCount: template.reviewCount,
    tags: [...template.tags, 'DEMO Template'],
    verified: false,
    pipelineStage: template.contact.hasWebsite ? 'new' : 'hot',
    status: 'new',
    incomingAt: Date.now(),
  };

  const fullLead: Lead = {
    ...baseLead,
    generatedWebsite: generateClientWebsite(baseLead),
  };

  registerLead(fullLead);
  return fullLead;
}
