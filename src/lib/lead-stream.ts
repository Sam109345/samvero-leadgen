let streamCounter = 0;

/**
 * Returns a new realistic incoming lead with calculated business age and pre-synthesized website
 */
export function generateNextIncomingLead(): Lead {
  const template = incomingLeadTemplates[streamCounter % incomingLeadTemplates.length];
  streamCounter++;

  const id = `stream-lead-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`;
  const businessAge = calculateBusinessAge(template.foundedDate);

  const baseLead: Lead = {
    id,
    title: template.title,
    businessName: template.businessName,
    type: template.type,
    platform: template.platform,
    category: template.category,
    country: template.country,
    city: template.city,
    address: template.address,
    businessAge,
    budget: template.budget,
    jobType: template.jobType,
    description: template.description,
    postedAt: 'Just now',
    contact: template.contact,
    rating: template.rating,
    reviewCount: template.reviewCount,
    tags: template.tags,
    verified: true,
    pipelineStage: template.contact.hasWebsite ? 'new' : 'hot',
    status: 'new',
    incomingAt: Date.now(),
  };

  const fullLead: Lead = {
    ...baseLead,
    generatedWebsite: generateClientWebsite(baseLead),
  };

  registerLead(fullLead);
  return fullLead;
}
